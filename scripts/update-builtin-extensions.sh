#!/bin/bash
# Refreshes the built-in extensions (crates/muxy-app/builtin-extensions) from
# https://github.com/muxy-app/extensions. Builds each one with the upstream
# tooling, copies its build output into place, and records the commit in
# UPSTREAM.toml. Usage: scripts/update-builtin-extensions.sh [git ref]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REF="${1:-main}"
REPOSITORY="https://github.com/muxy-app/extensions"
DESTINATION="$ROOT/crates/muxy-app/builtin-extensions"
NAMES=(files git)

for tool in git node npm rsync; do
    if ! command -v "$tool" >/dev/null; then
        echo "Error: $tool is required" >&2
        exit 1
    fi
done

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
SOURCE="$WORK/extensions"

git clone --quiet "$REPOSITORY" "$SOURCE"
git -C "$SOURCE" checkout --quiet "$REF"
COMMIT="$(git -C "$SOURCE" rev-parse HEAD)"

# The upstream build installs the locked dependencies without lifecycle
# scripts, runs each extension's `build`, and checks the manifest's files exist.
(cd "$SOURCE" && npm ci --ignore-scripts --no-audit --no-fund && node scripts/build.mjs "${NAMES[@]}")

{
    echo "# Generated by scripts/update-builtin-extensions.sh; do not edit."
    echo "repository = \"$REPOSITORY\""
    echo "ref = \"$REF\""
    echo "commit = \"$COMMIT\""
} > "$WORK/UPSTREAM.toml"

for name in "${NAMES[@]}"; do
    dist="$SOURCE/extensions/$name/dist"
    # Screenshots are only shown by the marketplace; logs are written at runtime.
    rsync -a --delete --exclude '/screenshots/' --exclude '/logs/' --exclude '.DS_Store' \
        "$dist/" "$DESTINATION/$name/"
    version="$(node -p 'require(process.argv[1]).version' "$DESTINATION/$name/package.json")"
    {
        echo
        echo "[extensions.$name]"
        echo "version = \"$version\""
        echo "path = \"extensions/$name\""
    } >> "$WORK/UPSTREAM.toml"
done

mv "$WORK/UPSTREAM.toml" "$DESTINATION/UPSTREAM.toml"
echo "Updated ${NAMES[*]} to $COMMIT ($(du -sh "$DESTINATION" | cut -f1))"
